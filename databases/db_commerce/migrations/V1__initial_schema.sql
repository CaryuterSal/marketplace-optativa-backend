CREATE TABLE IF NOT EXISTS country (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code CHAR(2) NOT NULL UNIQUE
);


CREATE TABLE IF NOT EXISTS postal_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code CHAR(5) NOT NULL,
    country_id BIGINT NOT NULL REFERENCES country(id)
);


CREATE TABLE IF NOT EXISTS phone_numbers (
    rest_number VARCHAR(45) NOT NULL,
    validated_at TIMESTAMP NULL,
    country_id BIGINT NOT NULL REFERENCES country(id),
    PRIMARY KEY (rest_number, country_id)
);


CREATE TABLE IF NOT EXISTS validation_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code CHAR(5) NOT NULL,
    phone_numbers_country_code CHAR(2) NOT NULL,
    phone_numbers_rest_number VARCHAR(45) NOT NULL
);


CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(45) NOT NULL UNIQUE,
    first_name VARCHAR(45) NOT NULL,
    last_name VARCHAR(45) NOT NULL,
    birthday DATE NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NULL,
    deleted_at TIMESTAMP NULL,
    phone_numbers_country_code CHAR(2) NULL,
    phone_numbers_rest_number VARCHAR(45) NULL
);


CREATE TABLE IF NOT EXISTS sellers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rfc VARCHAR(45) NOT NULL,
    users_id BIGINT NOT NULL REFERENCES users(id)
);


CREATE TABLE IF NOT EXISTS address (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state VARCHAR(45) NOT NULL,
    city VARCHAR(45) NOT NULL,
    street VARCHAR(45) NOT NULL,
    ext_num VARCHAR(10) NOT NULL,
    int_num VARCHAR(10) NULL,
    comments VARCHAR(500) NULL,
    postal_codes_id BIGINT NOT NULL REFERENCES postal_codes(id),
    users_id BIGINT NOT NULL REFERENCES users(id),
    geo_point POINT NULL
);


CREATE TABLE IF NOT EXISTS payment_methods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR(20) NOT NULL
        CHECK (provider IN ('STRIPE', 'PAYPAL', 'MERCADOPAGO')),
    payment_type VARCHAR(20) NOT NULL
        CHECK (payment_type IN ('CREDIT_CARD', 'DEBIT_CARD', 'TRANSFER')),
    provider_token VARCHAR(255) NOT NULL,
    card_brand VARCHAR(20) NULL
        CHECK (card_brand IN ('VISA', 'MASTERCARD', 'AMEX')),
    card_last_four CHAR(4) NULL,
    exp_month INT NULL,
    exp_year INT NULL,
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NULL,
    users_id BIGINT NOT NULL REFERENCES users(id),
    billing_address_id BIGINT NOT NULL REFERENCES address(id)
);


CREATE TABLE IF NOT EXISTS carts (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NULL,
    users_id BIGINT NOT NULL REFERENCES users(id)
);


CREATE TABLE IF NOT EXISTS cart_items (
    id VARCHAR(45) PRIMARY KEY,
    carts_id INT NOT NULL REFERENCES carts(id),
    products_id BIGINT NOT NULL,
    quantity INT NOT NULL
);


CREATE TABLE IF NOT EXISTS orders (
    carts_id INT PRIMARY KEY REFERENCES carts(id),
    users_id BIGINT NOT NULL REFERENCES users(id),
    payment_methods_id BIGINT NOT NULL REFERENCES payment_methods(id),
    status VARCHAR(45) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NULL,
    total DECIMAL(13,2) NOT NULL,
    subtotal DECIMAL(13,2) NOT NULL,
    discount_total DECIMAL(13,2) NOT NULL,
    shipping_total DECIMAL(13,2) NOT NULL
);


CREATE TABLE IF NOT EXISTS order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_items_id VARCHAR(45) NULL,
    products_id BIGINT NOT NULL,
    quantity INT NOT NULL,
    unit_price DECIMAL(13,2) NOT NULL,
    final_price DECIMAL(13,2) NOT NULL,
    order_carts_id INT NOT NULL REFERENCES orders(carts_id)
);


CREATE TABLE IF NOT EXISTS shipping_methods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(45) NOT NULL,
    carrier VARCHAR(45) NOT NULL,
    estimated_days INT NOT NULL,
    base_cost DECIMAL(13,2) NOT NULL
);


CREATE TABLE IF NOT EXISTS shipments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tracking_number VARCHAR(100) NOT NULL,
    shipping_cost DECIMAL(13,2) NOT NULL,
    status VARCHAR(30) NOT NULL,
    shipped_at TIMESTAMP NULL,
    estimated_delivered_at TIMESTAMP NULL,
    delivered_at TIMESTAMP NULL,
    order_carts_id INT NOT NULL REFERENCES orders(carts_id),
    shipping_methods_id BIGINT NOT NULL REFERENCES shipping_methods(id),
    sellers_id BIGINT NOT NULL REFERENCES sellers(id),
    address_id BIGINT NOT NULL REFERENCES address(id)
);


CREATE TABLE IF NOT EXISTS shipment_items (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantity INT NOT NULL,
    shipments_id BIGINT NOT NULL REFERENCES shipments(id),
    order_items_id BIGINT NOT NULL REFERENCES order_items(id)
);


